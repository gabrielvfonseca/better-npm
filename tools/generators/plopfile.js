import { execSync } from "node:child_process"

export default function (plop) {
  // ──────────────────────────────────────────────
  // Custom Handlebars Helpers
  // ──────────────────────────────────────────────

  plop.setHelper("pascalCase", (str) => {
    return str
      .replace(/[^a-zA-Z0-9]+/g, " ")
      .replace(/(?:^\w|[A-Z]|\b\w)/g, (word, index) =>
        index === 0 ? word.toUpperCase() : word.toUpperCase(),
      )
      .replace(/\s+/g, "")
  })

  plop.setHelper("camelCase", (str) => {
    return str
      .replace(/[^a-zA-Z0-9]+/g, " ")
      .replace(/(?:^\w|[A-Z]|\b\w)/g, (word, index) =>
        index === 0 ? word.toLowerCase() : word.toUpperCase(),
      )
      .replace(/\s+/g, "")
  })

  plop.setHelper("snakeCase", (str) => {
    return str
      .replace(/[^a-zA-Z0-9]+/g, "_")
      .replace(/^_+|_+$/g, "")
      .toLowerCase()
  })

  plop.setHelper("dotCase", (str) => {
    return str
      .replace(/[^a-zA-Z0-9]+/g, ".")
      .replace(/^\.+|\.+$/g, "")
      .toLowerCase()
  })

  plop.setHelper("pluralize", (str) => {
    if (/[sxz]$/i.test(str) || /[^aeioudgkprt]h$/i.test(str)) {
      return str + "es"
    }
    if (/[^aeiou]y$/i.test(str)) {
      return str.slice(0, -1) + "ies"
    }
    return str + "s"
  })

  plop.setHelper("upperCase", (str) => String(str).toUpperCase())
  plop.setHelper("lowerCase", (str) => String(str).toLowerCase())
  plop.setHelper("trim", (str) => String(str).trim())

  plop.setHelper("eq", function (a, b) {
    return a === b
  })

  plop.setHelper("or", function (a, b) {
    return a || b
  })

  plop.setHelper("and", function (a, b) {
    return a && b
  })

  plop.setHelper("not", function (a) {
    return !a
  })

  plop.setHelper("ifEquals", function (a, b, opts) {
    return a === b ? opts.fn(this) : opts.inverse(this)
  })

  plop.setHelper("relative", (depth) => {
    const n = Number.parseInt(depth, 10)
    if (Number.isNaN(n) || n <= 0) return "./"
    return "../".repeat(n)
  })

  plop.setHelper("split", function (str, separator) {
    if (!str) return []
    return String(str).split(separator || ",").map((s) => s.trim())
  })

  plop.setHelper("timestamp", () => {
    const now = new Date()
    const year = now.getFullYear()
    const month = String(now.getMonth() + 1).padStart(2, "0")
    const day = String(now.getDate()).padStart(2, "0")
    const hours = String(now.getHours()).padStart(2, "0")
    const minutes = String(now.getMinutes()).padStart(2, "0")
    const seconds = String(now.getSeconds()).padStart(2, "0")
    return `${year}${month}${day}${hours}${minutes}${seconds}`
  })

  // ──────────────────────────────────────────────
  // Partials
  // ──────────────────────────────────────────────

  plop.setPartial("license", "// MIT License\n// Copyright (c) {{year}} Dash\n// Permission is hereby granted...")

  plop.setPartial(
    "jshint",
    "/* jshint esversion: 11 */\n/* global console, process, require */",
  )

  plop.setPartial("shebang", "#!/usr/bin/env node\n")

  plop.setPartial(
    "auto-generated",
    "// ------------------------------------------------------------------\n// This file is auto-generated by Dash generators.\n// Changes may be overwritten. Edit the generator template instead.\n// ------------------------------------------------------------------\n",
  )

  // ──────────────────────────────────────────────
  // Custom Action Types
  // ──────────────────────────────────────────────

  plop.setActionType("runBunInstall", function (_answers, _config, _plop) {
    execSync("bun install", { cwd: process.cwd(), stdio: "inherit" })
    return "bun install completed"
  })

  plop.setActionType("runCargoCheck", function (answers, _config, _plop) {
    const cratePath = `crates/${answers.name.replace(/\s+/g, "-")}`
    execSync(`cargo check -p dash-${answers.name.replace(/\s+/g, "-")}`, {
      cwd: process.cwd(),
      stdio: "inherit",
    })
    return `cargo check passed for ${cratePath}`
  })

  plop.setActionType("format", function (_answers, _config, _plop) {
    execSync("bunx @biomejs/biome format --write .", {
      cwd: process.cwd(),
      stdio: "inherit",
    })
    return "biome format completed"
  })

  // ──────────────────────────────────────────────
  // Generators
  // ──────────────────────────────────────────────

  plop.setGenerator("package", {
    description: "Create a new package",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Package name (dash-case):",
        validate: (input) => (input ? true : "Package name is required"),
      },
      {
        type: "input",
        name: "description",
        message: "Package description:",
      },
      {
        type: "list",
        name: "scope",
        message: "Package scope:",
        choices: ["@dash", "@dash-internal"],
        default: "@dash",
      },
    ],
    actions: [
      {
        type: "addMany",
        destination: "packages/{{dashCase name}}",
        templateFiles: "tools/generators/package/templates/**/*",
        base: "tools/generators/package/templates",
      },
      {
        type: "modify",
        pattern: /(\/\/ Path aliases for packages)/,
        path: "tsconfig.json",
        template:
          "$1\n// @dash/{{dashCase name}} -> ./packages/{{dashCase name}}/src",
      },
    ],
  })

  plop.setGenerator("app", {
    description: "Create a new application",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "App name (dash-case):",
        validate: (input) => (input ? true : "App name is required"),
      },
      {
        type: "input",
        name: "description",
        message: "App description:",
      },
      {
        type: "list",
        name: "framework",
        message: "Framework:",
        choices: ["nextjs", "hono", "fastify", "express", "worker"],
        default: "hono",
      },
    ],
    actions: [
      {
        type: "addMany",
        destination: "apps/{{dashCase name}}",
        templateFiles: "tools/templates/new-app/**/*",
        base: "tools/templates/new-app",
      },
    ],
  })

  plop.setGenerator("component", {
    description: "Create a new React component",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Component name (PascalCase):",
        validate: (input) => {
          if (!input) return "Component name is required"
          if (!/^[A-Z][a-zA-Z0-9]*$/.test(input))
            return "Must be PascalCase (e.g., Button, UserAvatar)"
          return true
        },
      },
      {
        type: "input",
        name: "description",
        message: "Component description:",
      },
      {
        type: "confirm",
        name: "hasProps",
        message: "Generate props interface?",
        default: true,
      },
      {
        type: "confirm",
        name: "hasTests",
        message: "Generate test file?",
        default: true,
      },
      {
        type: "confirm",
        name: "hasStory",
        message: "Generate Storybook story?",
        default: false,
      },
    ],
    actions: function (data) {
      const actions = []

      actions.push({
        type: "addMany",
        destination: "packages/ui/src/components/{{pascalCase name}}",
        templateFiles: "tools/generators/component/templates/**/*",
        base: "tools/generators/component/templates",
        skipIfExists: true,
      })

      if (!data.hasTests) {
        actions.push({
          type: "modify",
          path: "packages/ui/src/components/{{pascalCase name}}/{{pascalCase name}}.test.tsx",
          skip: () => "Skipping test file",
        })
        actions.push({
          type: "add",
          path: "packages/ui/src/components/{{pascalCase name}}/.test-skip",
          skip: () => true,
        })
      }

      if (!data.hasStory) {
        actions.push({
          type: "modify",
          path: "packages/ui/src/components/{{pascalCase name}}/{{pascalCase name}}.stories.tsx",
          skip: () => "Skipping story file",
        })
      }

      return actions
    },
  })

  plop.setGenerator("hook", {
    description: "Create a new React hook",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Hook name (camelCase, e.g., useMediaQuery):",
        validate: (input) => {
          if (!input) return "Hook name is required"
          if (!/^use[A-Z][a-zA-Z0-9]*$/.test(input))
            return "Must be camelCase starting with 'use' (e.g., useMediaQuery)"
          return true
        },
      },
      {
        type: "input",
        name: "description",
        message: "Hook description:",
      },
      {
        type: "confirm",
        name: "hasTests",
        message: "Generate test file?",
        default: true,
      },
    ],
    actions: function (data) {
      const actions = [
        {
          type: "add",
          path: "packages/hooks/src/{{camelCase name}}.ts",
          templateFile: "tools/generators/hook/templates/hook.ts.hbs",
        },
      ]

      if (data.hasTests) {
        actions.push({
          type: "add",
          path: "packages/hooks/src/{{camelCase name}}.test.ts",
          templateFile: "tools/generators/hook/templates/hook.test.ts.hbs",
        })
      }

      return actions
    },
  })

  plop.setGenerator("crate", {
    description: "Create a new Rust crate",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Crate name (dash-case):",
        validate: (input) => {
          if (!input) return "Crate name is required"
          if (!/^[a-z][a-z0-9-]*$/.test(input))
            return "Must be dash-case (e.g., my-crate)"
          return true
        },
      },
      {
        type: "input",
        name: "description",
        message: "Crate description:",
      },
      {
        type: "list",
        name: "type",
        message: "Crate type:",
        choices: [
          { name: "Library (lib.rs)", value: "library" },
          { name: "Binary (main.rs)", value: "binary" },
        ],
        default: "library",
      },
      {
        type: "input",
        name: "dependencies",
        message: "Additional dependencies (comma-separated, e.g., serde,tokio):",
      },
    ],
    actions: function (data) {
      const actions = []

      actions.push({
        type: "add",
        path: "crates/{{dashCase name}}/Cargo.toml",
        templateFile: "tools/generators/crate/templates/Cargo.toml.hbs",
      })

      if (data.type === "binary") {
        actions.push({
          type: "add",
          path: "crates/{{dashCase name}}/src/main.rs",
          templateFile: "tools/generators/crate/templates/src/main.rs.hbs",
        })
      } else {
        actions.push({
          type: "add",
          path: "crates/{{dashCase name}}/src/lib.rs",
          templateFile: "tools/generators/crate/templates/src/lib.rs.hbs",
        })
      }

      actions.push({
        type: "runCargoCheck",
      })

      return actions
    },
  })

  plop.setGenerator("worker", {
    description: "Create a new worker",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Worker name (dash-case):",
        validate: (input) => (input ? true : "Worker name is required"),
      },
      {
        type: "input",
        name: "description",
        message: "Worker description:",
      },
      {
        type: "list",
        name: "queue_type",
        message: "Queue type:",
        choices: [
          { name: "Pub/Sub", value: "pubsub" },
          { name: "Queue", value: "queue" },
          { name: "Cron / Scheduled", value: "cron" },
        ],
        default: "queue",
      },
    ],
    actions: [
      {
        type: "addMany",
        destination: "apps/workers/{{dashCase name}}",
        templateFiles: "tools/generators/worker/templates/**/*",
        base: "tools/generators/worker/templates",
      },
    ],
  })

  plop.setGenerator("migration", {
    description: "Create a new database migration",
    prompts: [
      {
        type: "input",
        name: "name",
        message: "Migration name (snake_case):",
        validate: (input) => (input ? true : "Migration name is required"),
      },
      {
        type: "input",
        name: "description",
        message: "Migration description:",
      },
    ],
    actions: [
      {
        type: "add",
        path: "database/migrations/{{timestamp}}_{{snakeCase name}}.sql",
        templateFile: "tools/generators/migration/templates/migration.sql.hbs",
      },
    ],
  })
}
